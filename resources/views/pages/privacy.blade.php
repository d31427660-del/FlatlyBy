<script>
function switchSection(btnElement, sectionId) {
  // Toggle nav buttons active class
  document.querySelectorAll('.legal-nav-btn').forEach(btn => {
    btn.classList.remove('active');
  });
  btnElement.classList.add('active');

  // Hide all sections
  document.querySelectorAll('.legal-section').forEach(sec => {
    sec.classList.remove('active');
  });

  // Show selected section
  if (sectionId === 'privacy') {
    document.getElementById('sec-privacy').classList.add('active');
  } else if (sectionId === 'offer') {
    document.getElementById('sec-offer').classList.add('active');
  } else if (sectionId === 'cookies') {
    document.getElementById('sec-cookies').classList.add('active');
  }
  
  // Smooth scroll content area to top on mobile
  if (window.innerWidth <= 768) {
    document.querySelector('.legal-content-card').scrollIntoView({ behavior: 'smooth' });
  }
}

document.addEventListener('DOMContentLoaded', function() {
  function handleHash() {
    const hash = window.location.hash.substring(1);
    if (hash === 'offer' || hash === 'cookies' || hash === 'privacy') {
      const btn = document.querySelector(`.legal-nav-btn[onclick*="'${hash}'"]`);
      if (btn) {
        switchSection(btn, hash);
      }
    }
  }
  handleHash();
  window.addEventListener('hashchange', handleHash);
});

</script>
